const switcher = document.getElementById("languageSwitcher");
const languageUi = document.querySelector("[data-language-ui]");
const languageCurrent = languageUi ? languageUi.querySelector(".flag-current") : null;
const languageCurrentIcon = languageCurrent ? languageCurrent.querySelector(".flag-icon") : null;
const languageOptions = languageUi ? Array.from(languageUi.querySelectorAll("[data-lang-option]")) : [];
const languageFlagClasses = {
  vi: "flag-vn",
  en: "flag-us",
  zh: "flag-cn",
  hi: "flag-in"
};

function updateLanguageUi(lang) {
  const flagClass = languageFlagClasses[lang] || languageFlagClasses.vi;

  if (languageCurrentIcon) {
    languageCurrentIcon.className = `flag-icon ${flagClass}`;
  }

  languageOptions.forEach((option) => {
    const isActive = option.dataset.langOption === lang;
    option.classList.toggle("is-active", isActive);
    option.setAttribute("aria-selected", String(isActive));
  });
}

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.vi;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-lang]").forEach((element) => {
    const key = element.dataset.lang;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-placeholder]").forEach((element) => {
    const key = element.dataset.placeholder;
    if (dictionary[key]) {
      element.placeholder = dictionary[key];
    }
  });

  localStorage.setItem("l38_lang", lang);
  updateLanguageUi(lang);
}

if (switcher) {
  const savedLanguage = localStorage.getItem("l38_lang") || "vi";
  switcher.value = translations[savedLanguage] ? savedLanguage : "vi";
  setLanguage(switcher.value);
  switcher.addEventListener("change", (event) => setLanguage(event.target.value));
}

if (languageUi && languageCurrent) {
  const closeLanguageMenu = () => {
    languageUi.classList.remove("open");
    languageCurrent.setAttribute("aria-expanded", "false");
  };

  languageCurrent.addEventListener("click", () => {
    const isOpen = languageUi.classList.toggle("open");
    languageCurrent.setAttribute("aria-expanded", String(isOpen));
  });

  languageOptions.forEach((option) => {
    option.addEventListener("click", () => {
      const lang = option.dataset.langOption;
      if (!lang || !switcher) return;

      switcher.value = lang;
      switcher.dispatchEvent(new Event("change", { bubbles: true }));
      closeLanguageMenu();
    });
  });

  document.addEventListener("click", (event) => {
    if (!languageUi.contains(event.target)) {
      closeLanguageMenu();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeLanguageMenu();
    }
  });
}
